function enrichFile(file, tag) {
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  let introSet = 0, orgFilled = 0, matched = 0;
  const missing = [];
  for (const it of data.items) {
    const e = ENRICH[it.id];
    if (!e) { if (it.recognition !== '未认定' && !it.custom) missing.push(it.id); continue; }
    matched++;
    if (e.intro && it.intro !== e.intro) { it.intro = e.intro; introSet++; }
    if (e.organizer && !it.organizer) { it.organizer = e.organizer; orgFilled++; }
    if (e.site && !it.site) it.site = e.site;
    if (e.window && !it.window) it.window = e.window;
  }
  data.introNote = '简介为工具内置整理（2026-09），主办方与时间以赛事官网为准。';
  data.libVersion = '2026.09.1';
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(`[${tag}] matched=${matched} introSet=${introSet} orgFilled=${orgFilled} 未覆盖=${missing.length}`);
  if (missing.length) console.log(`[${tag}] 未覆盖 id: ${missing.join(', ')}`);
}

